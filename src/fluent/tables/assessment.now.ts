import { BooleanColumn, ChoiceColumn, DateColumn, IntegerColumn, GenericColumn, DecimalColumn, MultiLineTextColumn, ReferenceColumn, StringColumn, Table } from '@servicenow/sdk/core'
import { AGING_FLAGS, ASSESSMENT_STATES, ASSESSMENT_TYPES, CA_STATES, CA_TYPES, FINDING_STATES, FUNDING_STATUSES, ROOT_CAUSES, SEVERITIES } from '../../server/lib/domain'

/** One EPAS assessment event (annual internal or triennial USAEC external) at an installation. */
export const x_cog_env_assessment = Table({
    name: 'x_cog_env_assessment',
    label: 'EPAS assessment',
    audit: true,
    display: 'number',
    schema: {
        number: StringColumn({ label: 'Number', maxLength: 40, default: 'javascript:global.getNextObjNumberPadded();', readOnly: true }),
        installation: ReferenceColumn({ label: 'Installation', referenceTable: 'x_cog_env_installation', mandatory: true }),
        assessment_type: ChoiceColumn({ label: 'Type', choices: ASSESSMENT_TYPES, default: 'internal', dropdown: 'dropdown_without_none' }),
        fiscal_year: IntegerColumn({ label: 'Fiscal year', mandatory: true }),
        state: ChoiceColumn({ label: 'State', choices: ASSESSMENT_STATES, default: 'planned', dropdown: 'dropdown_without_none' }),
        team_lead: ReferenceColumn({ label: 'Team lead', referenceTable: 'sys_user' }),
        start_date: DateColumn({ label: 'Fieldwork start' }),
        end_date: DateColumn({ label: 'Fieldwork end' }),
        finalization_due: DateColumn({ label: 'Report finalization due', readOnly: true }),
        finalized_on: DateColumn({ label: 'Finalized on', readOnly: true }),
        scope_notes: MultiLineTextColumn({ label: 'Scope / media assessed', maxLength: 4000 }),
        findings_total: IntegerColumn({ label: 'Findings', default: 0, readOnly: true }),
        findings_significant: IntegerColumn({ label: 'Significant', default: 0, readOnly: true }),
        findings_major: IntegerColumn({ label: 'Major', default: 0, readOnly: true }),
        findings_minor: IntegerColumn({ label: 'Minor', default: 0, readOnly: true }),
        findings_repeat: IntegerColumn({ label: 'Repeat findings', default: 0, readOnly: true }),
        work_notes: GenericColumn({ label: 'Work notes', columnType: 'journal_input' }),
        active: BooleanColumn({ label: 'Active', default: true }),
    },
    autoNumber: { prefix: 'EPA', number: 1000, numberOfDigits: 7 },
    allowWebServiceAccess: true,
    actions: { read: true, create: true, update: true, delete: true },
})

/** A compliance finding raised during an assessment. Evidence is attached with sys_attachment. */
export const x_cog_env_finding = Table({
    name: 'x_cog_env_finding',
    label: 'Finding',
    audit: true,
    display: 'number',
    schema: {
        number: StringColumn({ label: 'Number', maxLength: 40, default: 'javascript:global.getNextObjNumberPadded();', readOnly: true }),
        assessment: ReferenceColumn({ label: 'Assessment', referenceTable: 'x_cog_env_assessment', mandatory: true }),
        installation: ReferenceColumn({ label: 'Installation', referenceTable: 'x_cog_env_installation', readOnly: true }),
        program_area: ReferenceColumn({ label: 'Program area', referenceTable: 'x_cog_env_program_area', mandatory: true }),
        regulatory_driver: ReferenceColumn({ label: 'Regulatory driver', referenceTable: 'x_cog_env_regulatory_driver' }),
        enforcement_action: ReferenceColumn({ label: 'Enforcement action', referenceTable: 'x_cog_env_enforcement_action' }),
        title: StringColumn({ label: 'Finding', maxLength: 160, mandatory: true }),
        description: MultiLineTextColumn({ label: 'Description / condition observed', maxLength: 4000 }),
        location: StringColumn({ label: 'Location (building / site)', maxLength: 120 }),
        severity: ChoiceColumn({ label: 'Severity', choices: SEVERITIES, default: 'minor', dropdown: 'dropdown_without_none' }),
        root_cause: ChoiceColumn({ label: 'Root cause', choices: ROOT_CAUSES, dropdown: 'dropdown_with_none' }),
        state: ChoiceColumn({ label: 'State', choices: FINDING_STATES, default: 'open', dropdown: 'dropdown_without_none' }),
        repeat_finding: BooleanColumn({ label: 'Repeat finding', default: false, readOnly: true }),
        previous_finding: ReferenceColumn({ label: 'Previous finding', referenceTable: 'x_cog_env_finding', readOnly: true }),
        identified_on: DateColumn({ label: 'Identified on', mandatory: true }),
        closure_due: DateColumn({ label: 'Closure due', readOnly: true }),
        closed_on: DateColumn({ label: 'Closed on', readOnly: true }),
        closed_by: ReferenceColumn({ label: 'Closed by', referenceTable: 'sys_user', readOnly: true }),
        closure_justification: MultiLineTextColumn({ label: 'Closure / risk acceptance justification', maxLength: 4000 }),
        days_open: IntegerColumn({ label: 'Days open', default: 0, readOnly: true }),
        aging_flag: ChoiceColumn({ label: 'Aging', choices: AGING_FLAGS, default: 'green', dropdown: 'dropdown_without_none', readOnly: true }),
        assigned_to: ReferenceColumn({ label: 'Assigned to', referenceTable: 'sys_user' }),
        work_notes: GenericColumn({ label: 'Work notes', columnType: 'journal_input' }),
        active: BooleanColumn({ label: 'Active', default: true }),
    },
    index: [
        { name: 'idx_finding_installation_state', unique: false, element: 'installation' },
        { name: 'idx_finding_assessment', unique: false, element: 'assessment' },
    ],
    autoNumber: { prefix: 'EPF', number: 1000, numberOfDigits: 7 },
    allowWebServiceAccess: true,
    actions: { read: true, create: true, update: true, delete: true },
})

